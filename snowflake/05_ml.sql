-- Feed-refusal risk scoring and feed demand forecast over the synthetic snapshot.
-- Predicts P(feed-refusal event in the next 7 days) per pond and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.FEED_REFUSAL_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.POND_AGE_YEARS,
       r.UNEATEN_FEED_KG, r.HOPPER_LEVEL_PCT,
       AVG(r.UNEATEN_FEED_KG) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS UNEATEN_FEED_7D,
       SUM(r.FEED_REFUSAL_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS FEED_REFUSALS_30D,
       IFF(SUM(r.FEED_REFUSAL_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'FEED_REFUSAL', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.POND_DAILY r JOIN RAW.PONDS t ON t.ID = r.ENTITY_ID
-- City-wide water events are not pond-driven, so they are excluded from training.
WHERE r.ROOT_CAUSE NOT IN ('Salinity intrusion', 'Heat wave') OR r.FEED_REFUSAL_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.FEED_REFUSAL_TRAIN AS
SELECT CATEGORY, POND_AGE_YEARS, UNEATEN_FEED_KG, HOPPER_LEVEL_PCT, UNEATEN_FEED_7D, FEED_REFUSALS_30D, LABEL
FROM ML.FEED_REFUSAL_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.FEED_REFUSAL_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, POND_AGE_YEARS, UNEATEN_FEED_KG, HOPPER_LEVEL_PCT, UNEATEN_FEED_7D, FEED_REFUSALS_30D, LABEL
FROM ML.FEED_REFUSAL_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.FEED_REFUSAL_RISK_MODEL(
  INPUT_DATA => TABLE(ML.FEED_REFUSAL_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.FEED_REFUSAL_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.FEED_REFUSAL_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'POND_AGE_YEARS', POND_AGE_YEARS, 'UNEATEN_FEED_KG', UNEATEN_FEED_KG,
           'HOPPER_LEVEL_PCT', HOPPER_LEVEL_PCT, 'UNEATEN_FEED_7D', UNEATEN_FEED_7D, 'FEED_REFUSALS_30D', FEED_REFUSALS_30D)):probability:FEED_REFUSAL::FLOAT AS P
  FROM ML.FEED_REFUSAL_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'FEED_REFUSAL', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'FEED_REFUSAL', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'FEED_REFUSAL', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'FEED_REFUSAL', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per pond (label unknown, so excluded from features).
CREATE TABLE ML.FEED_REFUSAL_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.FEED_REFUSAL_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.FEED_REFUSAL_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'POND_AGE_YEARS', POND_AGE_YEARS, 'UNEATEN_FEED_KG', UNEATEN_FEED_KG,
           'HOPPER_LEVEL_PCT', HOPPER_LEVEL_PCT, 'UNEATEN_FEED_7D', UNEATEN_FEED_7D, 'FEED_REFUSALS_30D', FEED_REFUSALS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:FEED_REFUSAL::FLOAT, 4) AS FEED_REFUSAL_PROB_7D,
       CASE WHEN P:probability:FEED_REFUSAL::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:FEED_REFUSAL::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Grower-wide daily feed demand forecast (14 days, tonnes) from the daily series.
CREATE VIEW ML.DAILY_FEED AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(FEED_TONNES)::FLOAT AS FEED_TONNES
FROM RAW.POND_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.FEED_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_FEED),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'FEED_TONNES'
);

CREATE TABLE ML.FEED_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, ROUND(FORECAST, 1) AS FEED_TONNES,
       ROUND(GREATEST(0, LOWER_BOUND), 1) AS LOWER_BOUND, ROUND(UPPER_BOUND, 1) AS UPPER_BOUND
FROM TABLE(ML.FEED_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
