-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT pnd.ID AS ENTITY_ID, pnd.NAME AS ENTITY_NAME,
       pnd.REGION, pnd.CATEGORY, pnd.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(o.FEED_REFUSAL_COUNT) AS FEED_REFUSAL_COUNT,
       SUM(o.OPERATING_HOURS) AS OPERATING_HOURS, SUM(o.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(o.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(o.RATION_REVIEW_DUE) AS RATION_REVIEW_DUE, SUM(o.RATION_REVIEW_DONE) AS RATION_REVIEW_DONE,
       SUM(o.FEED_TONNES) AS FEED_TONNES, SUM(o.BIOMASS_GAIN_KG) AS BIOMASS_GAIN_KG,
       SUM(o.TRAYS_CLEARED) AS TRAYS_CLEARED, SUM(o.TRAYS_CHECKED) AS TRAYS_CHECKED,
       SUM(o.LOW_DO_ALERTS) AS LOW_DO_ALERTS,
       100.0 * SUM(o.TRAYS_CLEARED) / NULLIF(SUM(o.TRAYS_CHECKED), 0) AS UPTAKE_PCT,
       SUM(o.BIOMASS_GAIN_KG) / NULLIF(SUM(o.FEED_TONNES), 0) AS GAIN_KG_PER_T,
       100.0 * SUM(o.OPERATING_HOURS) / NULLIF(SUM(o.PLANNED_HOURS), 0) AS FEEDER_UPTIME_PCT,
       100.0 * SUM(o.RATION_REVIEW_DONE) / NULLIF(SUM(o.RATION_REVIEW_DUE), 0) AS RATION_REVIEW_COMPLETION_PCT,
       MAX(o.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.POND_DAILY o
JOIN RAW.PONDS pnd ON pnd.ID = o.ENTITY_ID
GROUP BY pnd.ID, pnd.NAME, pnd.REGION, pnd.CATEGORY, pnd.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(TRAYS_CLEARED) AS TRAYS_CLEARED, SUM(TRAYS_CHECKED) AS TRAYS_CHECKED,
       SUM(FEED_TONNES) AS FEED_TONNES, SUM(BIOMASS_GAIN_KG) AS BIOMASS_GAIN_KG,
       SUM(LOW_DO_ALERTS) AS LOW_DO_ALERTS, SUM(FEED_REFUSAL_COUNT) AS FEED_REFUSAL_COUNT,
       100.0 * SUM(TRAYS_CLEARED) / NULLIF(SUM(TRAYS_CHECKED), 0) AS UPTAKE_PCT,
       SUM(BIOMASS_GAIN_KG) / NULLIF(SUM(FEED_TONNES), 0) AS GAIN_KG_PER_T
FROM RAW.POND_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.FEED_REFUSAL_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(FEED_REFUSAL_COUNT) AS FEED_REFUSAL_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(TRAYS_CHECKED) - SUM(TRAYS_CLEARED) AS UNCLEARED_TRAYS
FROM RAW.POND_DAILY
WHERE FEED_REFUSAL_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(TRAYS_CLEARED) AS TRAYS_CLEARED, SUM(TRAYS_CHECKED) AS TRAYS_CHECKED,
         SUM(FEED_TONNES) AS FEED_TONNES, SUM(BIOMASS_GAIN_KG) AS BIOMASS_GAIN_KG,
         SUM(LOW_DO_ALERTS) AS LOW_DO_ALERTS, SUM(FEED_REFUSAL_COUNT) AS FEED_REFUSALS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.POND_DAILY
), ponds AS (SELECT COUNT(*) AS POND_COUNT FROM RAW.PONDS),
coverage AS (
  SELECT 100.0 * SUM(LEAST(AUTOFEEDER_HA, POND_HA)) / NULLIF(SUM(POND_HA), 0) AS AUTOFEEDER_PCT
  FROM RAW.FEEDER_COVERAGE
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Feed Uptake Rate' AS TITLE,
         100.0 * TRAYS_CLEARED / NULLIF(TRAYS_CHECKED, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Feed-Refusal Events', FEED_REFUSALS, '' FROM observations
  UNION ALL SELECT 3, 'Feed Efficiency', BIOMASS_GAIN_KG / NULLIF(FEED_TONNES, 0), ' kg gain/t feed' FROM observations
  UNION ALL SELECT 4, 'Feed Dispensed (t)', FEED_TONNES, '' FROM observations
  UNION ALL SELECT 5, 'Auto-Feeder Uptime', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Ponds Monitored', POND_COUNT, '' FROM ponds
  UNION ALL SELECT 7, 'Auto-Feeder Coverage', AUTOFEEDER_PCT, '%' FROM coverage
  UNION ALL SELECT 8, 'Low-Oxygen Alerts', LOW_DO_ALERTS, '' FROM observations
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '999,990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.FEED_REFUSAL_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
